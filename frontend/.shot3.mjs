import { chromium } from "@playwright/test";
const [,, out1, out2] = process.argv;
const b = await chromium.launch();
const p = await b.newPage({ viewport: { width: 1500, height: 1100 } });
const errs = [];
p.on("pageerror", e => errs.push(String(e)));
await p.goto("http://localhost:3000/approvals", { waitUntil: "networkidle" });
await p.waitForTimeout(2500);
await p.screenshot({ path: out1, fullPage: true });
await p.getByRole("button", { name: "Approve", exact: true }).first().click();
await p.waitForTimeout(700);
await p.screenshot({ path: out2 });
console.log(errs.length ? "ERRORS " + errs.join("\n") : "ok");
await b.close();
